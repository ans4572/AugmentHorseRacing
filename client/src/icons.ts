export type IconName = keyof typeof PATHS;

/** 아이콘 SVG 문자열 (innerHTML 용) */
export function icon(name: IconName, cls = ''): string {
  return `<svg class="ic${cls ? ' ' + cls : ''}" viewBox="0 0 24 24" aria-hidden="true" focusable="false"><path fill="currentColor" fill-rule="evenodd" d="${PATHS[name]}"/></svg>`;
}

/** index.html 안의 <i data-ic="이름"></i> 자리를 아이콘으로 바꾼다 */
export function mountIcons(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>('i[data-ic]').forEach((el) => {
    const name = el.dataset.ic as IconName;
    if (PATHS[name]) el.outerHTML = icon(name, el.className);
  });
}

/** 순위 표시 — 1~3위는 색이 다른 로제트, 그 아래는 숫자만 */
export function rankBadge(rank: number): string {
  return `<span class="rank-badge${rank <= 3 ? ' r' + rank : ''}">${rank}</span>`;
}

/**
 * 이 바탕색 위에 어두운 잉크 글씨를 써야 하면 true.
 * 실제 번호 안장처럼 밝은 색 천에는 검은 숫자, 어두운 색 천에는 흰 숫자를 쓴다.
 */
export function inkOn(hex: string): boolean {
  const c = [1, 3, 5]
    .map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  const lum = 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
  return lum > 0.25;
}

/** 번호 안장 — 말을 가리키는 모든 곳에서 같은 모양으로 쓴다 */
export function bib(id: number, color: string, size: '' | 'sm' | 'lg' = ''): string {
  return `<span class="bib${size ? ' ' + size : ''}${inkOn(color) ? ' dk' : ''}" style="background:${color}">${id}</span>`;
}
